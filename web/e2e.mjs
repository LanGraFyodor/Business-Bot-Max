import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
await fs.mkdir(fileURLToPath(new URL('../artifacts/',import.meta.url)),{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>localStorage.setItem('docspace-section',JSON.stringify('documents')));
 await page.goto('http://127.0.0.1:8082',{waitUntil:'domcontentloaded'});
 await page.getByRole('heading',{name:'Все документы'}).waitFor();
 if(await page.getByRole('listitem').count()<6)throw Error('seed documents missing');
 await page.screenshot({path:fileURLToPath(new URL('../artifacts/teams-desktop.png',import.meta.url)),fullPage:true});
 await page.getByRole('combobox',{name:'Рабочая команда'}).selectOption('studio');
 await page.getByRole('heading',{name:'Все документы'}).waitFor();
 await page.getByRole('button',{name:'общее',exact:false}).first().click();
 await page.getByRole('button',{name:'Обсуждение'}).first().click();
 await page.getByRole('textbox',{name:'Сообщение в канал'}).fill('Проверка чата команды');
 await page.getByRole('button',{name:'Отправить сообщение'}).click();
 await page.locator('.chat-message p').filter({hasText:'Проверка чата команды'}).last().waitFor();
 await page.getByRole('combobox',{name:'Рабочая команда'}).selectOption('orbita');
 await page.getByRole('listitem').first().getByRole('button').first().click();
 await page.getByRole('dialog',{name:/Договор на разработку сайта|Счёт на оплату/}).waitFor();
 await page.getByRole('button',{name:'Назад к документам'}).click();
 await page.setViewportSize({width:390,height:844});
 await page.reload({waitUntil:'domcontentloaded'});
 await page.getByRole('heading',{name:'Все документы'}).waitFor();
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('horizontal mobile overflow');
 await page.screenshot({path:fileURLToPath(new URL('../artifacts/teams-mobile.png',import.meta.url)),fullPage:true});
 await page.getByRole('button',{name:'Открыть команды и каналы'}).click();
 await page.getByRole('combobox',{name:'Рабочая команда'}).selectOption('studio');
 await page.getByRole('button',{name:'Закрыть каналы'}).click();
 await page.getByRole('button',{name:'Загрузить документ',exact:true}).first().click();
 await page.getByRole('dialog',{name:'Новый документ'}).waitFor();
 await page.locator('input[type=file]').first().setInputFiles({name:'Смета.txt',mimeType:'text/plain',buffer:Buffer.from('Смета на запуск проекта')});
 await page.getByRole('button',{name:'Загрузить документ'}).last().click();
 await page.getByRole('dialog',{name:'Смета'}).waitFor();
 await page.screenshot({path:fileURLToPath(new URL('../artifacts/teams-mobile-document.png',import.meta.url)),fullPage:true});
 await page.getByRole('button',{name:'Обсуждение'}).last().click();
 await page.getByRole('textbox',{name:'Комментарий'}).fill('Нужно уточнить бюджет');
 await page.getByRole('button',{name:'Отправить комментарий'}).click();
 await page.getByText('Нужно уточнить бюджет').waitFor();
 await page.getByRole('button',{name:'На согласование'}).click();
 await page.getByRole('button',{name:'Согласовать'}).click();
 await page.getByText('Согласовано',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Назад к документам'}).click();
 await page.getByRole('button',{name:'Открыть команды и каналы'}).click();
 await page.locator('.navigation.is-open .user-panel').click();
 await page.getByRole('combobox',{name:'Проверить от лица'}).selectOption('2');
 await page.getByRole('heading',{name:'Все документы'}).waitFor();
 await page.getByRole('button',{name:'Открыть команды и каналы'}).click();
 if(await page.locator('select[aria-label="Рабочая команда"] option[value="studio"]').count()!==0)throw Error('other team visible to employee');
 await page.getByRole('button',{name:'Закрыть каналы'}).click();
 if(errors.length)throw Error('JS errors: '+errors.join('; '));
 console.log('Desktop + mobile, two teams, chat, document, approval, role isolation: PASS');
}finally{await browser.close()}
